revise_file() {
    TMP=`mktemp`
    local state=0
    while read -r line; do 
        case $state in
        	0)
        	if [[ "$line" =~ \<p\ class=\"stanza\"\> ]]; then
        	    if [[ "$line" =~ \</p\> ]]; then
        	    	echo "$line" >> $TMP
        	        continue
        	    else
        	    	echo "$line" >> $TMP
        	        state=1
        	    fi
        	else
        		echo "$line" >> $TMP
        	fi
        	;;
            1)
            if [[ "$line" =~ \</p\> ]]; then
            	echo "$line" >> $TMP
                state=0
            elif [[ "$line" =~ ^\<span\ class=\"line ]]; then
            	echo "$line" >> $TMP
                state=2
            else
            	echo "$line" >> $TMP
            fi
            ;;
            2)
            if [[ "$line" =~ \</p\> ]]; then
            	echo "$line" >> $TMP
                state=0
            elif [[ "$line" =~ ^\<span\ class=\"page\"\>[^\<\>]+\</span\>$ ]]; then
                echo -n "$line" >> $TMP
            else
                echo "$line" >> $TMP
            fi   
            ;;         
        esac 
    done < "$1"
    mv "$TMP" "$1"
}
for file in "${files[@]}"; do
    revise_file "$file"
done
